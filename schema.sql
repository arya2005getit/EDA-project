-- Re-runnable schema setup. Drop child tables before their parent tables.
DROP TABLE IF EXISTS billing CASCADE;
DROP TABLE IF EXISTS admissions CASCADE;
DROP TABLE IF EXISTS patients CASCADE;
DROP TABLE IF EXISTS insurance_providers CASCADE;
DROP TABLE IF EXISTS doctors CASCADE;
DROP TABLE IF EXISTS diseases CASCADE;
DROP TABLE IF EXISTS departments CASCADE;
DROP TABLE IF EXISTS cities CASCADE;

-- Lookup table of the cities where patients live.
CREATE TABLE cities (
    city_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name VARCHAR(100) NOT NULL UNIQUE
);

-- Lookup table of hospital departments.
CREATE TABLE departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE
);

-- Each disease belongs to one department, as verified in the source data.
CREATE TABLE diseases (
    disease_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disease_name VARCHAR(120) NOT NULL UNIQUE,
    department_id BIGINT NOT NULL,
    CONSTRAINT diseases_department_fk FOREIGN KEY (department_id)
        REFERENCES departments (department_id) ON DELETE RESTRICT
);

-- Doctors are stored independently because the source shows each doctor in multiple departments.
CREATE TABLE doctors (
    doctor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_name VARCHAR(120) NOT NULL UNIQUE
);

-- Lookup table for insurance companies. Uninsured bills have a NULL provider_id.
CREATE TABLE insurance_providers (
    provider_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_name VARCHAR(120) NOT NULL UNIQUE
);

-- One row per person; patient_id retains the original values such as P001.
CREATE TABLE patients (
    patient_id VARCHAR(20) PRIMARY KEY,
    patient_name VARCHAR(120) NOT NULL,
    age SMALLINT NOT NULL CHECK (age BETWEEN 0 AND 120),
    gender VARCHAR(10) NOT NULL CHECK (gender IN ('Male', 'Female')),
    city_id BIGINT NOT NULL,
    CONSTRAINT patients_city_fk FOREIGN KEY (city_id)
        REFERENCES cities (city_id) ON DELETE RESTRICT
);

-- One row for each hospital admission. Department is reached through disease_id.
CREATE TABLE admissions (
    admission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id VARCHAR(20) NOT NULL,
    doctor_id BIGINT NOT NULL,
    disease_id BIGINT NOT NULL,
    admission_date DATE NOT NULL,
    discharge_date DATE NOT NULL,
    stay_days INTEGER NOT NULL CHECK (stay_days >= 0),
    CONSTRAINT admissions_dates_check CHECK (discharge_date >= admission_date),
    CONSTRAINT admissions_patient_fk FOREIGN KEY (patient_id)
        REFERENCES patients (patient_id) ON DELETE RESTRICT,
    CONSTRAINT admissions_doctor_fk FOREIGN KEY (doctor_id)
        REFERENCES doctors (doctor_id) ON DELETE RESTRICT,
    CONSTRAINT admissions_disease_fk FOREIGN KEY (disease_id)
        REFERENCES diseases (disease_id) ON DELETE RESTRICT
);

-- One bill belongs to one admission. A NULL provider means the admission was uninsured.
CREATE TABLE billing (
    bill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_id BIGINT NOT NULL UNIQUE,
    provider_id BIGINT,
    bill_amount NUMERIC(12, 2) NOT NULL CHECK (bill_amount >= 0),
    payment_status VARCHAR(10) NOT NULL CHECK (payment_status IN ('Paid', 'Pending')),
    CONSTRAINT billing_admission_fk FOREIGN KEY (admission_id)
        REFERENCES admissions (admission_id) ON DELETE RESTRICT,
    CONSTRAINT billing_provider_fk FOREIGN KEY (provider_id)
        REFERENCES insurance_providers (provider_id) ON DELETE RESTRICT
);

-- Table and column comments explain their roles to future readers.
COMMENT ON TABLE cities IS 'Lookup list of patient cities.';
COMMENT ON COLUMN cities.city_id IS 'Generated primary key for a city.';
COMMENT ON COLUMN cities.city_name IS 'Unique city name from the source data.';
COMMENT ON TABLE departments IS 'Lookup list of hospital departments.';
COMMENT ON COLUMN departments.department_id IS 'Generated primary key for a department.';
COMMENT ON COLUMN departments.department_name IS 'Unique department name.';
COMMENT ON TABLE diseases IS 'Disease lookup; each disease maps to one department.';
COMMENT ON COLUMN diseases.disease_id IS 'Generated primary key for a disease.';
COMMENT ON COLUMN diseases.disease_name IS 'Unique disease name.';
COMMENT ON COLUMN diseases.department_id IS 'Department that treats this disease.';
COMMENT ON TABLE doctors IS 'Doctor lookup, independent of department.';
COMMENT ON COLUMN doctors.doctor_id IS 'Generated primary key for a doctor.';
COMMENT ON COLUMN doctors.doctor_name IS 'Unique doctor name.';
COMMENT ON TABLE insurance_providers IS 'Lookup list of insurance providers.';
COMMENT ON COLUMN insurance_providers.provider_id IS 'Generated primary key for a provider.';
COMMENT ON COLUMN insurance_providers.provider_name IS 'Unique insurance provider name.';
COMMENT ON TABLE patients IS 'One row per patient, with city stored by foreign key.';
COMMENT ON COLUMN patients.patient_id IS 'Original patient identifier, for example P001.';
COMMENT ON COLUMN patients.patient_name IS 'Patient display name; it is not a key.';
COMMENT ON COLUMN patients.age IS 'Age in years, constrained to the range 0 through 120.';
COMMENT ON COLUMN patients.gender IS 'Gender limited to the two values in the cleaned source.';
COMMENT ON COLUMN patients.city_id IS 'City where the patient lives.';
COMMENT ON TABLE admissions IS 'One row per hospital visit or admission.';
COMMENT ON COLUMN admissions.admission_id IS 'Generated primary key for an admission.';
COMMENT ON COLUMN admissions.patient_id IS 'Patient receiving this admission.';
COMMENT ON COLUMN admissions.doctor_id IS 'Doctor assigned to this admission.';
COMMENT ON COLUMN admissions.disease_id IS 'Disease; its department is found through diseases.';
COMMENT ON COLUMN admissions.admission_date IS 'Date the patient was admitted.';
COMMENT ON COLUMN admissions.discharge_date IS 'Date the patient was discharged.';
COMMENT ON COLUMN admissions.stay_days IS 'Number of days between admission and discharge.';
COMMENT ON TABLE billing IS 'Bill and payment status for an admission.';
COMMENT ON COLUMN billing.bill_id IS 'Generated primary key for a bill.';
