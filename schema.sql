COMMENT ON COLUMN billing.bill_amount IS 'Bill total in the source currency, stored with two decimal places.';
COMMENT ON COLUMN billing.payment_status IS 'Payment state, limited to Paid or Pending.';

-- Index foreign keys for joins and lookups, plus admission date for date filtering.
CREATE INDEX diseases_department_id_idx ON diseases (department_id);
CREATE INDEX patients_city_id_idx ON patients (city_id);
CREATE INDEX admissions_patient_id_idx ON admissions (patient_id);
CREATE INDEX admissions_doctor_id_idx ON admissions (doctor_id);
CREATE INDEX admissions_disease_id_idx ON admissions (disease_id);
CREATE INDEX admissions_admission_date_idx ON admissions (admission_date);
CREATE INDEX billing_admission_id_idx ON billing (admission_id);
CREATE INDEX billing_provider_id_idx ON billing (provider_id);
