"""
03_etl_load.py
==============
Reads hospital_clean.csv, splits the data into eight normalised tables,
and loads them into PostgreSQL in the correct parent-before-child order.

The entire load runs inside a single database transaction — if anything
fails, the whole operation is rolled back so the database stays clean.

Usage
-----
  python 03_etl_load.py                        # load into existing tables
  python 03_etl_load.py --create-schema        # run schema.sql first
  python 03_etl_load.py --reset                # clear existing data, then load
  python 03_etl_load.py --create-schema --reset  # drop & recreate, then load
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import pandas as pd
from dotenv import load_dotenv
from sqlalchemy import URL, create_engine, text
from sqlalchemy.exc import SQLAlchemyError


# ---------------------------------------------------------------------------
# File paths
# ---------------------------------------------------------------------------
BASE_DIR    = Path(__file__).resolve().parent
CSV_FILE    = BASE_DIR / "hospital_clean.csv"
SCHEMA_FILE = BASE_DIR / "schema.sql"

# ---------------------------------------------------------------------------
# Table configuration
# ---------------------------------------------------------------------------

# Tables must be loaded in this order so parent rows exist before child rows
TABLES_IN_LOAD_ORDER = [
    "cities", "departments", "diseases", "doctors", "insurance_providers",
    "patients", "admissions", "billing",
]

# These tables use GENERATED BY DEFAULT identity columns; we set explicit IDs
# so the load is repeatable, then advance the sequence afterward
IDENTITY_COLUMNS = {
    "cities":              "city_id",
    "departments":         "department_id",
    "diseases":            "disease_id",
    "doctors":             "doctor_id",
    "insurance_providers": "provider_id",
    "admissions":          "admission_id",
}

# Expected column names in the clean CSV (must match exactly)
SOURCE_COLUMNS = [
    "patient_id", "patient_name", "age", "gender", "disease", "department",
    "doctor", "admission_date", "discharge_date", "stay_days", "bill_amount",
    "insurance", "insurance_provider", "city", "payment_status",
]


# ---------------------------------------------------------------------------
# Database connection
# ---------------------------------------------------------------------------

def make_engine():
    """
    Read database credentials from the .env file and open a connection.
    Raises RuntimeError with a clear message if any credentials are missing
    or the connection test fails.
    """
    load_dotenv(BASE_DIR / ".env")

    required_vars = ["PGHOST", "PGDATABASE", "PGUSER", "PGPASSWORD"]
    missing_vars  = [name for name in required_vars if not os.getenv(name)]

    if missing_vars:
        raise RuntimeError(
            "Database settings are missing: " + ", ".join(missing_vars)
            + ". Copy .env.example to .env and fill in your PostgreSQL settings."
        )

    connection_url = URL.create(
        "postgresql+psycopg2",
        username=os.environ["PGUSER"],
        password=os.environ["PGPASSWORD"],
        host=os.environ["PGHOST"],
        port=int(os.getenv("PGPORT", "5432")),
        database=os.environ["PGDATABASE"],
    )

    engine = create_engine(connection_url, future=True)

    # Verify the connection works before proceeding
    try:
        with engine.connect() as connection:
            connection.execute(text("SELECT 1"))
    except SQLAlchemyError as error:
        engine.dispose()
        raise RuntimeError(
            "Could not connect to PostgreSQL. Check that the server is running "
            "and that PGHOST, PGPORT, PGDATABASE, PGUSER, and PGPASSWORD are correct.\n"
            f"Database error: {error}"
        ) from error

    print("Connected to PostgreSQL.")
    return engine


# ---------------------------------------------------------------------------
# Extract – read and validate the CSV
# ---------------------------------------------------------------------------

def extract_csv():
    """
    Read the clean CSV and do basic sanity checks before we touch the database.
    Raises ValueError immediately if the file looks wrong, so the database is
    never partially modified.
    """
    print("\n=== EXTRACT ===")

    if not CSV_FILE.exists():
        raise FileNotFoundError(f"CSV file not found: {CSV_FILE}")

    data = pd.read_csv(
        CSV_FILE,
        dtype={"patient_id": "string"},
        parse_dates=["admission_date", "discharge_date"],
    )

    # Check that the columns are exactly what we expect
    if list(data.columns) != SOURCE_COLUMNS:
        raise ValueError(f"CSV columns do not match expected columns: {list(data.columns)}")

    # We expect exactly 300 patient rows
    if len(data) != 300:
        raise ValueError(f"Expected 300 CSV rows, found {len(data)}. Nothing was loaded.")

    # patient_id must exist and be non-blank for every row
    if data["patient_id"].isna().any() or data["patient_id"].str.strip().eq("").any():
        raise ValueError("patient_id contains a missing or blank value. Nothing was loaded.")

    # patient_id must be unique (one row per patient in this dataset)
    if data["patient_id"].duplicated().any():
        duplicate_ids = data.loc[data["patient_id"].duplicated(False), "patient_id"].tolist()
        raise ValueError(f"patient_id is not unique: {duplicate_ids}. Nothing was loaded.")

    # Blank insurance_provider cells should be NULL in the database, not empty strings
    data["insurance_provider"] = data["insurance_provider"].replace(r"^\s*$", pd.NA, regex=True)

    print(f"Read {len(data)} rows. patient_id is present and unique in every row.")
    return data


# ---------------------------------------------------------------------------
# Transform helpers
# ---------------------------------------------------------------------------

def assign_sorted_ids(values):
    """
    Create a stable name-to-integer ID mapping by sorting the unique values
    alphabetically and assigning IDs starting at 1.
    Returns a dict like {"Cardiology": 1, "Neurology": 2, ...}.
    Using sorted order makes IDs repeatable across runs.
    """
    return {name: number for number, name in enumerate(sorted(set(values)), start=1)}


def map_required(series, lookup_dict, description):
    """
    Replace each value in the Series with its integer ID from lookup_dict.
    Raises ValueError if any value has no matching ID, so we catch foreign-key
    problems before the database does.
    """
    mapped = series.map(lookup_dict)

    if mapped.isna().any():
        unmapped_values = series.loc[mapped.isna()].drop_duplicates().tolist()
        raise ValueError(f"Unmapped {description} values: {unmapped_values}")

    return mapped.astype("int64")


# ---------------------------------------------------------------------------
# Transform – build one DataFrame per table
# ---------------------------------------------------------------------------

def transform(data):
    """
    Split the flat CSV into one clean DataFrame per database table.
    Each lookup table (cities, departments, etc.) gets stable integer IDs
    derived from alphabetical sort order so the result is repeatable.
    """
    print("\n=== TRANSFORM ===")

    # --- Lookup tables ---

    # Cities
    city_ids = assign_sorted_ids(data["city"].dropna().tolist())
    cities   = pd.DataFrame({
        "city_id":   list(city_ids.values()),
        "city_name": list(city_ids.keys()),
    })

    # Departments
    department_ids = assign_sorted_ids(data["department"].dropna().tolist())
    departments    = pd.DataFrame({
        "department_id":   list(department_ids.values()),
        "department_name": list(department_ids.keys()),
    })

    # Diseases — each disease is linked to exactly one department
    disease_pairs     = data[["disease", "department"]].drop_duplicates()
    dept_count_per_disease = disease_pairs.groupby("disease")["department"].nunique(dropna=False)
    if not dept_count_per_disease.eq(1).all():
        bad_diseases = dept_count_per_disease[dept_count_per_disease.ne(1)].to_dict()
        raise ValueError(f"A disease maps to more than one department: {bad_diseases}")

    disease_names     = sorted(disease_pairs["disease"].dropna().unique().tolist())
    disease_ids       = {name: number for number, name in enumerate(disease_names, start=1)}
    disease_to_dept   = disease_pairs.drop_duplicates("disease").set_index("disease")["department"]

    diseases = pd.DataFrame({
        "disease_id":     [disease_ids[name] for name in disease_names],
        "disease_name":   disease_names,
        "department_id":  [department_ids[disease_to_dept[name]] for name in disease_names],
    })

    # Doctors
    doctor_ids = assign_sorted_ids(data["doctor"].dropna().tolist())
    doctors    = pd.DataFrame({
        "doctor_id":   list(doctor_ids.values()),
        "doctor_name": list(doctor_ids.keys()),
    })

    # Insurance providers (only rows with a provider; uninsured patients have NULL)
    provider_names = sorted(data["insurance_provider"].dropna().unique().tolist())
    provider_ids   = {name: number for number, name in enumerate(provider_names, start=1)}
    insurance_providers = pd.DataFrame({
        "provider_id":   list(provider_ids.values()),
        "provider_name": provider_names,
    })

    # --- Core tables ---

    # Patients (demographic info + city)
    patients = (
        data[["patient_id", "patient_name", "age", "gender", "city"]]
        .drop_duplicates("patient_id")
        .sort_values("patient_id")
        .copy()
    )
    patients["city_id"] = map_required(patients["city"], city_ids, "city")
    patients = patients[["patient_id", "patient_name", "age", "gender", "city_id"]]
    patients["age"] = pd.to_numeric(patients["age"], errors="raise").astype("int64")

    # Admissions (one row per hospital visit)
    admissions = (
        data[["patient_id", "doctor", "disease", "admission_date", "discharge_date", "stay_days"]]
        .sort_values("patient_id")
        .reset_index(drop=True)
        .copy()
    )
    # Assign explicit admission IDs (1, 2, 3, …) so they are deterministic
    admissions.insert(0, "admission_id", range(1, len(admissions) + 1))
    admissions["doctor_id"]  = map_required(admissions["doctor"],  doctor_ids,  "doctor")
    admissions["disease_id"] = map_required(admissions["disease"], disease_ids, "disease")
    admissions["stay_days"]  = pd.to_numeric(admissions["stay_days"], errors="raise").astype("int64")
    admissions = admissions[[
        "admission_id", "patient_id", "doctor_id", "disease_id",
        "admission_date", "discharge_date", "stay_days",
    ]]

    # Build a patient_id → admission_id lookup for the billing table
    admission_id_by_patient = dict(zip(admissions["patient_id"], admissions["admission_id"]))

    # Billing (financial info linked to an admission)
    billing = data[["patient_id", "insurance_provider", "bill_amount", "payment_status"]].copy()
    billing["admission_id"] = map_required(billing["patient_id"], admission_id_by_patient, "admission")

    # Only insured rows get a provider_id; uninsured rows keep NULL
    has_provider = billing["insurance_provider"].notna()
    billing["provider_id"] = pd.Series(index=billing.index, dtype="object")
    billing.loc[has_provider, "provider_id"] = map_required(
        billing.loc[has_provider, "insurance_provider"], provider_ids, "insurance provider"
    )

    billing["bill_amount"] = pd.to_numeric(billing["bill_amount"], errors="raise")
    billing = billing[["admission_id", "provider_id", "bill_amount", "payment_status"]]
    billing = billing.sort_values("admission_id").reset_index(drop=True)

    # --- Collect all tables and convert pandas NA to Python None (= SQL NULL) ---
    tables = {
        "cities":              cities,
        "departments":         departments,
        "diseases":            diseases,
        "doctors":             doctors,
        "insurance_providers": insurance_providers,
        "patients":            patients,
        "admissions":          admissions,
        "billing":             billing,
    }

    for table_name, table_df in tables.items():
        # Replace pandas NA/NaN with Python None so SQLAlchemy writes SQL NULL
        tables[table_name] = table_df.astype(object).where(pd.notna(table_df), None)
        print(f"  Prepared '{table_name}': {len(table_df)} rows")

    return tables


# ---------------------------------------------------------------------------
# Load helpers
# ---------------------------------------------------------------------------

def get_table_presence(connection):
    """
    Check which of the expected tables already exist in the public schema.
    Returns a dict like {"cities": True, "billing": False, ...}.
    """
    return {
        table: connection.execute(
            text("SELECT to_regclass(:table_name) IS NOT NULL"),
            {"table_name": f"public.{table}"},
        ).scalar_one()
        for table in TABLES_IN_LOAD_ORDER
    }


def get_row_counts(connection):
    """Read the current row count for each table."""
    return {
        table: connection.execute(
            text(f'SELECT COUNT(*) FROM "{table}"')
        ).scalar_one()
        for table in TABLES_IN_LOAD_ORDER
    }


def execute_schema(connection):
    """
    Parse schema.sql and run each SQL statement inside the current transaction.
    We parse manually so that semicolons inside quoted strings or identifiers
    do not accidentally split a statement.
    """
    if not SCHEMA_FILE.exists():
        raise FileNotFoundError(f"Schema file not found: {SCHEMA_FILE}")

    print("Running schema.sql inside the load transaction.")
    schema_text = SCHEMA_FILE.read_text(encoding="utf-8")

    # --- Manual SQL statement splitter ---
    # We track whether we are inside a quoted string/identifier so we only
    # split on semicolons that are actual statement terminators.
    statements    = []
    current_chars = []
    inside_single_quote = False
    inside_double_quote = False
    inside_line_comment = False
    index = 0

    while index < len(schema_text):
        char      = schema_text[index]
        next_char = schema_text[index + 1] if index + 1 < len(schema_text) else ""

        if inside_line_comment:
            current_chars.append(char)
            if char == "\n":
                inside_line_comment = False

        elif inside_single_quote:
            current_chars.append(char)
            if char == "'":
                if next_char == "'":          # escaped single quote ''
                    current_chars.append(next_char)
                    index += 1
                else:
                    inside_single_quote = False

        elif inside_double_quote:
            current_chars.append(char)
            if char == '"':
                if next_char == '"':          # escaped double quote ""
                    current_chars.append(next_char)
                    index += 1
                else:
                    inside_double_quote = False

        elif char == "-" and next_char == "-":     # start of -- comment
            current_chars.extend([char, next_char])
            index += 1
            inside_line_comment = True

        elif char == "'":
            current_chars.append(char)
            inside_single_quote = True

        elif char == '"':
            current_chars.append(char)
            inside_double_quote = True

        elif char == ";":                          # real statement terminator
            statement = "".join(current_chars).strip()
            if statement:
                statements.append(statement)
            current_chars = []

        else:
            current_chars.append(char)

        index += 1

    if inside_single_quote or inside_double_quote:
        raise ValueError("schema.sql contains an unterminated quoted value or identifier")

    # Append any trailing content after the last semicolon
    tail = "".join(current_chars).strip()
    if tail:
        statements.append(tail)

    # Run each statement (skip comment-only segments)
    for statement in statements:
        executable = "\n".join(
            line for line in statement.splitlines()
            if line.strip() and not line.lstrip().startswith("--")
        ).strip()
        if executable:
            connection.exec_driver_sql(statement)


def advance_identity_sequences(connection):
    """
    Move each identity sequence counter past the highest ID we inserted.
    This is needed because we inserted explicit IDs (instead of letting the
    database auto-generate them) to make the load repeatable.
    """
    for table, column in IDENTITY_COLUMNS.items():
        statement = text(
            "SELECT setval(pg_get_serial_sequence(:qualified_table, :column_name), "
            f'(SELECT COALESCE(MAX("{column}"), 1) FROM "{table}"), '
            f'EXISTS (SELECT 1 FROM "{table}"))'
        )
        connection.execute(statement, {
            "qualified_table": f"public.{table}",
            "column_name":     column,
        })


def write_load_report(row_counts):
    """Write a brief Markdown summary of how many rows were inserted per table."""
    table_rows = "\n".join(
        f"| `{table}` | {count} |"
        for table, count in row_counts.items()
    )
    report_content = (
        "# ETL and database load report\n\n"
        "## What the ETL does\n\n"
        "Reads the cleaned CSV, validates the patient key, builds lookup tables with "
        "repeatable IDs, and loads parent tables before child tables. "
        "The entire load runs in one transaction — an error rolls everything back.\n\n"
        "## Rows inserted in the latest successful load\n\n"
        "| Table | Rows inserted |\n|---|---:|\n"
        f"{table_rows}\n\n"
        "## Validation\n\n"
        "Validation has not run yet. After loading, run `python 04_validate_load.py`; "
        "that script updates this section with the check results.\n"
    )
    (BASE_DIR / "etl_report.md").write_text(report_content, encoding="utf-8")


# ---------------------------------------------------------------------------
# Load – insert all tables inside one transaction
# ---------------------------------------------------------------------------

def load_tables(engine, tables, reset=False, create_schema=False):
    """
    Check the current state of the database, optionally clear it,
    and bulk-insert all eight tables atomically.

    Parameters
    ----------
    reset         : if True, truncate existing data before inserting.
    create_schema : if True, run schema.sql before inserting.
    """
    print("\n=== LOAD ===")
    try:
        with engine.begin() as connection:

            # --- Optionally create or recreate the schema ---
            presence = get_table_presence(connection)
            tables_already_exist = sum(presence.values())

            if create_schema:
                if tables_already_exist and not reset:
                    raise RuntimeError(
                        "--create-schema will DROP existing tables via schema.sql. "
                        "Add --reset to confirm you want to replace existing data."
                    )
                execute_schema(connection)
                presence = get_table_presence(connection)

            # Stop immediately if required tables are missing
            missing_tables = [name for name, exists in presence.items() if not exists]
            if missing_tables:
                raise RuntimeError(
                    "Required tables are missing: " + ", ".join(missing_tables)
                    + ". Run with --create-schema to create them."
                )

            # --- Optionally clear existing rows ---
            current_row_counts = get_row_counts(connection)

            if reset:
                print("--reset supplied: clearing existing rows and restarting identity counters.")
                # TRUNCATE in reverse dependency order; CASCADE handles FK constraints
                connection.exec_driver_sql(
                    "TRUNCATE TABLE billing, admissions, patients, diseases, "
                    "insurance_providers, doctors, departments, cities "
                    "RESTART IDENTITY CASCADE"
                )
            elif any(current_row_counts.values()):
                populated = {name: count for name, count in current_row_counts.items() if count}
                raise RuntimeError(
                    "Tables already contain data: " + str(populated)
                    + ". Use --reset only if you intend to replace that data."
                )

            # --- Insert each table in parent-before-child order ---
            inserted_counts = {}
            for table_name in TABLES_IN_LOAD_ORDER:
                tables[table_name].to_sql(
                    table_name,
                    con=connection,
                    if_exists="append",   # table already exists; we just add rows
                    index=False,
                    method="multi",       # batch inserts are faster than one row at a time
                    chunksize=500,
                )
                inserted_counts[table_name] = len(tables[table_name])
                print(f"  Inserted {inserted_counts[table_name]} rows into '{table_name}'.")

            # Advance sequences so future auto-generated IDs don't clash
            advance_identity_sequences(connection)

        # Transaction committed successfully at this point
        print("Transaction committed successfully.")
        write_load_report(inserted_counts)
        print(f"Load report written to {BASE_DIR / 'etl_report.md'}")
        return inserted_counts

    except Exception as error:
        print(f"Load failed; the transaction was rolled back. Reason: {error}")
        raise


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Split and load hospital_clean.csv into PostgreSQL."
    )
    parser.add_argument(
        "--reset", action="store_true",
        help="Clear existing rows before loading. Required if tables already have data.",
    )
    parser.add_argument(
        "--create-schema", action="store_true",
        help="Run schema.sql before loading (add --reset if tables already exist).",
    )
    args = parser.parse_args()

    # Extract → Transform → Load pipeline
    data   = extract_csv()
    tables = transform(data)
    engine = make_engine()

    try:
        load_tables(engine, tables, reset=args.reset, create_schema=args.create_schema)
    finally:
        engine.dispose()   # always close the connection pool cleanly


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        raise SystemExit(f"ETL stopped: {error}") from error
